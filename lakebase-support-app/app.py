"""
Lakebase-Powered AI Support App
A support ticket system that stores operational data in Lakebase (Databricks-managed Postgres).

Features:
- Create and manage support tickets
- Add messages to tickets
- Update ticket status
- View all tickets and their message history

Run locally:
    python app.py
Deploy as a Databricks App using app.yaml.
"""

import logging
import os
import uuid
from datetime import datetime

from databricks.sdk import WorkspaceClient
from flask import Flask, jsonify, render_template, request

import lakebase

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("support-app")

app = Flask(__name__)
_w = WorkspaceClient()

TICKETS_TABLE = os.environ.get("TICKETS_TABLE", "tickets")
MESSAGES_TABLE = os.environ.get("MESSAGES_TABLE", "ticket_messages")


def _current_user_email() -> str:
    """
    Resolve the current user's email.
    Databricks Apps inject the logged-in user's identity via the
    X-Forwarded-Email header on every request. Fall back to the Databricks
    SDK's current_user API for local development.
    """
    header_email = request.headers.get("X-Forwarded-Email")
    if header_email:
        return header_email
    return _w.current_user.me().user_name


def ensure_tables():
    """Create the tickets and ticket_messages tables if they don't exist."""
    
    # Create tickets table with auto-generated 6-char random ID
    lakebase.run_write(
        f"""
        CREATE TABLE IF NOT EXISTS {TICKETS_TABLE} (
            ticket_id TEXT PRIMARY KEY DEFAULT substring(md5(random()::text || clock_timestamp()::text), 1, 6),
            title TEXT NOT NULL,
            status TEXT NOT NULL DEFAULT 'open',
            priority TEXT NOT NULL DEFAULT 'medium',
            category TEXT NOT NULL DEFAULT 'general',
            created_by TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        )
        """
    )
    
    # Add priority and category columns if they don't exist (for existing tables)
    try:
        lakebase.run_write(
            f"ALTER TABLE {TICKETS_TABLE} ADD COLUMN IF NOT EXISTS priority TEXT NOT NULL DEFAULT 'medium'"
        )
        lakebase.run_write(
            f"ALTER TABLE {TICKETS_TABLE} ADD COLUMN IF NOT EXISTS category TEXT NOT NULL DEFAULT 'general'"
        )
    except Exception as e:
        logger.info(f"Columns may already exist: {e}")
    
    # Create ticket_messages table with auto-generated 6-char random ID
    lakebase.run_write(
        f"""
        CREATE TABLE IF NOT EXISTS {MESSAGES_TABLE} (
            message_id TEXT PRIMARY KEY DEFAULT substring(md5(random()::text || clock_timestamp()::text), 1, 6),
            ticket_id TEXT NOT NULL REFERENCES {TICKETS_TABLE}(ticket_id) ON DELETE CASCADE,
            message_text TEXT NOT NULL,
            author TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        )
        """
    )
    
    # Create index for faster ticket message lookups
    lakebase.run_write(
        f"""
        CREATE INDEX IF NOT EXISTS idx_{MESSAGES_TABLE}_ticket_id
        ON {MESSAGES_TABLE} (ticket_id, created_at DESC)
        """
    )


