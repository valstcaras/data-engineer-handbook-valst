@app.route("/tickets", methods=["GET"])
def get_tickets():
    """Get all tickets with basic info, with optional status filtering."""
    status_filter = request.args.get('status', '').strip().lower()
    
    query = f"""
        SELECT t.ticket_id, t.title, t.status, t.priority, t.category, t.created_by, t.created_at,
               COUNT(m.message_id) as message_count
        FROM {TICKETS_TABLE} t
        LEFT JOIN {MESSAGES_TABLE} m ON t.ticket_id = m.ticket_id
    """
    
    params = None
    if status_filter:
        query += " WHERE t.status = %s"
        params = (status_filter,)
    
    query += f"""
        GROUP BY t.ticket_id, t.title, t.status, t.priority, t.category, t.created_by, t.created_at
        ORDER BY t.created_at DESC
    """
    
    tickets = lakebase.run_query(query, params) if params else lakebase.run_query(query)
    return jsonify(tickets)


@app.route("/tickets/<ticket_id>", methods=["GET"])
def get_ticket(ticket_id):
    """Get a specific ticket with all its messages."""
    # Get ticket details
    tickets = lakebase.run_query(
        f"SELECT * FROM {TICKETS_TABLE} WHERE ticket_id = %s",
        (ticket_id,)
    )
    
    if not tickets:
        return jsonify({"error": "Ticket not found"}), 404
    
    ticket = tickets[0]
    
    # Get messages for this ticket
    messages = lakebase.run_query(
        f"""
        SELECT message_id, message_text, author, created_at
        FROM {MESSAGES_TABLE}
        WHERE ticket_id = %s
        ORDER BY created_at ASC
        """,
        (ticket_id,)
    )
    
    ticket['messages'] = messages
    return jsonify(ticket)


@app.route("/tickets", methods=["POST"])
def create_ticket():
    """Create a new support ticket."""
    if not request.is_json:
        return jsonify({"error": "Request must be JSON"}), 400
    
    title = request.json.get("title", "").strip()
    initial_message = request.json.get("message", "").strip()
    priority = request.json.get("priority", "medium").strip().lower()
    category = request.json.get("category", "general").strip().lower()
    
    if not title:
        return jsonify({"error": "Title is required"}), 400
    
    if not initial_message:
        return jsonify({"error": "Initial message is required"}), 400
    
    valid_priorities = ["low", "medium", "high", "critical"]
    if priority not in valid_priorities:
        return jsonify({"error": f"Priority must be one of: {', '.join(valid_priorities)}"}), 400
    
    valid_categories = ["general", "access", "cluster", "support", "billing", "other"]
    if category not in valid_categories:
        return jsonify({"error": f"Category must be one of: {', '.join(valid_categories)}"}), 400
    
    author = _current_user_email()
    
    # Create the ticket
    ticket_result = lakebase.run_write_returning(
        f"""
        INSERT INTO {TICKETS_TABLE} (title, status, priority, category, created_by)
        VALUES (%s, 'open', %s, %s, %s)
        RETURNING ticket_id, title, status, priority, category, created_by, created_at
        """,
        (title, priority, category, author)
    )
    
    if not ticket_result:
        return jsonify({"error": "Failed to create ticket"}), 500
    
    ticket = ticket_result[0]
    ticket_id = ticket['ticket_id']
    
    # Add the initial message
    lakebase.run_write(
        f"INSERT INTO {MESSAGES_TABLE} (ticket_id, message_text, author) VALUES (%s, %s, %s)",
        (ticket_id, initial_message, author)
    )
    
    return jsonify(ticket), 201


@app.route("/tickets/<ticket_id>/messages", methods=["POST"])
def add_message(ticket_id):
    """Add a message to an existing ticket."""
    if not request.is_json:
        return jsonify({"error": "Request must be JSON"}), 400
    
    message_text = request.json.get("message", "").strip()
    
    if not message_text:
        return jsonify({"error": "Message text is required"}), 400
    
    # Verify ticket exists
    tickets = lakebase.run_query(
        f"SELECT ticket_id FROM {TICKETS_TABLE} WHERE ticket_id = %s",
        (ticket_id,)
    )
    
    if not tickets:
        return jsonify({"error": "Ticket not found"}), 404
    
    author = _current_user_email()
    message_id = str(uuid.uuid4())
    
    # Insert the message
    message_result = lakebase.run_write_returning(
        f"""
        INSERT INTO {MESSAGES_TABLE} (message_id, ticket_id, message_text, author)
        VALUES (%s, %s, %s, %s)
        RETURNING message_id, ticket_id, message_text, author, created_at
        """,
        (message_id, ticket_id, message_text, author)
    )
    
    if not message_result:
        return jsonify({"error": "Failed to add message"}), 500
    
    return jsonify(message_result[0]), 201


@app.route("/tickets/<ticket_id>/status", methods=["PUT"])
def update_status(ticket_id):
    """Update the status of a ticket."""
    if not request.is_json:
        return jsonify({"error": "Request must be JSON"}), 400
    
    new_status = request.json.get("status", "").strip().lower()
    
    valid_statuses = ["open", "in_progress", "resolved", "closed"]
    if new_status not in valid_statuses:
        return jsonify({"error": f"Status must be one of: {', '.join(valid_statuses)}"}), 400
    
    # Update the status
    result = lakebase.run_write_returning(
        f"""
        UPDATE {TICKETS_TABLE}
        SET status = %s
        WHERE ticket_id = %s
        RETURNING ticket_id, title, status, created_by, created_at
        """,
        (new_status, ticket_id)
    )
    
    if not result:
        return jsonify({"error": "Ticket not found"}), 404
    
    return jsonify(result[0])


